function isometricPhase(week) {
  if (week <= 2) return { sets: 3, time: "20–30 сек", rest: 90 };
  if (week <= 4) return { sets: 3, time: "25–35 сек", rest: 90 };
  if (week <= 6) return { sets: 3, time: "35–45 сек", rest: 75 };
  if (week <= 8) return { sets: "3–4", time: "40–50 сек", rest: 75 };
  if (week <= 10) return { sets: 4, time: "50–60 сек", rest: 60 };
  return { sets: "4–5", time: "60 сек", rest: 60 };
}

// Тренировки Пн / Ср / Пт
function isometricDay(week, weekday) {
  if (weekday === 1 || weekday === 3 || weekday === 5) {
    return { kind: "isometric", phase: isometricPhase(week) };
  }
  return { kind: "rest" };
}

