// weekday: 1=Пн ... 7=Вс
function fatlossDay(branch, week, weekday) {
  const sets = week <= 5 ? 3 : 4;
  const earlyPhase = week <= 2;

  if (branch === "cardio") {
    if (earlyPhase) {
      if (weekday === 1) return { kind: "strength", workout: week % 2 === 1 ? "A" : "B", sets };
      if (weekday === 2 || weekday === 4) return { kind: "cardio", minutes: 40 };
      return { kind: "rest" };
    }
    // недели 3-8
    if (weekday === 1) return { kind: "strength", workout: week % 2 === 1 ? "A" : "B", sets };
    if (weekday === 2 || weekday === 4 || weekday === 6) {
      return { kind: "cardio", minutes: week <= 5 ? 45 : 60 };
    }
    return { kind: "rest" };
  }

  if (branch === "strength") {
    if (earlyPhase) {
      if (weekday === 1) return { kind: "strength", workout: week % 2 === 1 ? "A" : "B", sets };
      if (weekday === 2 || weekday === 4) return { kind: "cardio", minutes: 40 };
      return { kind: "rest" };
    }
    // недели 3-8: Фулбади А в Пн, Фулбади Б в Чт
    if (weekday === 1) return { kind: "strength", workout: "A", sets };
    if (weekday === 4) return { kind: "strength", workout: "B", sets };
    if (weekday === 2 || weekday === 6) {
      return { kind: "cardio", minutes: week <= 5 ? 50 : 60 };
    }
    return { kind: "rest" };
  }
}

